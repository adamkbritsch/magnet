#!/bin/bash
# Copy Magnet's automatic side to the NAS and (re)start it. Run from the Mac.
#
#   nas/automatic/deploy.sh            deploy and restart
#   nas/automatic/deploy.sh --token    also give this Mac the API token for Magnet
#
# Needs MAGNET_NAS_SSH (user@host) and MAGNET_NAS_DIR (a folder on the NAS) in the
# repo's local.env, and nas/automatic/site.env (see site.env.example). Secrets are
# generated on the NAS the first time and kept on every later deploy; none of them
# is ever printed. --token copies the API token straight into
# ~/Library/Application Support/Magnet/automatic-token (mode 600).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
[[ -f "$ROOT/local.env" ]] && { set -a; . "$ROOT/local.env"; set +a; }
: "${MAGNET_NAS_SSH:?set MAGNET_NAS_SSH (user@host) in local.env}"
: "${MAGNET_NAS_DIR:?set MAGNET_NAS_DIR (deploy folder on the NAS) in local.env}"
[[ -f "$HERE/site.env" ]] || { echo "nas/automatic/site.env is missing; copy site.env.example" >&2; exit 1; }
SSH=(ssh -o LogLevel=ERROR "$MAGNET_NAS_SSH")

echo "==> Copying to $MAGNET_NAS_SSH:$MAGNET_NAS_DIR"
# tar over ssh: some NAS firmwares restrict rsync to their shares.
COPYFILE_DISABLE=1 tar --no-xattrs -C "$HERE" --exclude __pycache__ \
    -cf - app formats docker-compose.yml setup_sonarr.py rollback_sonarr.py \
  | "${SSH[@]}" "mkdir -p '$MAGNET_NAS_DIR' && rm -rf '$MAGNET_NAS_DIR/app' && tar -C '$MAGNET_NAS_DIR' -xf -"

# site.env + secrets -> .env, keeping secrets that already exist.
"${SSH[@]}" "cd '$MAGNET_NAS_DIR' && umask 077 && python3 -c '
import os, secrets, sys
site = sys.stdin.read()
old = {}
if os.path.exists(\".env\"):
    for line in open(\".env\"):
        k, _, v = line.strip().partition(\"=\")
        old[k] = v
keep = {\"GATE_USER\": old.get(\"GATE_USER\") or \"sonarr\",
        \"GATE_PASS\": old.get(\"GATE_PASS\") or secrets.token_urlsafe(24),
        \"API_TOKEN\": old.get(\"API_TOKEN\") or secrets.token_urlsafe(32)}
with open(\".env.tmp\", \"w\") as f:
    f.write(site.rstrip() + \"\n\n# generated by deploy.sh\n\")
    f.writelines(f\"{k}={v}\n\" for k, v in keep.items())
os.replace(\".env.tmp\", \".env\")
os.chmod(\".env\", 0o600)
'" < "$HERE/site.env"

"${SSH[@]}" bash -s <<REMOTE
set -euo pipefail
cd '$MAGNET_NAS_DIR'
DATA=\$(grep '^AUTOMATIC_DATA=' .env | cut -d= -f2-)
PUIDV=\$(grep '^PUID=' .env | cut -d= -f2-); PGIDV=\$(grep '^PGID=' .env | cut -d= -f2-)
if [[ ! -d "\$DATA" ]]; then
  docker run --rm -v "\$(dirname "\$DATA")":/v python:3.12-alpine sh -c "mkdir -p /v/\$(basename "\$DATA")/rollback && chown -R \${PUIDV:-1000}:\${PGIDV:-1000} /v/\$(basename "\$DATA") && chmod 750 /v/\$(basename "\$DATA")"
  echo "    created \$DATA"
fi
# Season folders: the TV library mounted at Sonarr's own paths -- every folder Sonarr
# and Plex both see, read from the two containers' mounts -- so a path means the same
# thing to all three. Written as an override beside docker-compose.yml.
python3 - <<'PY'
import json, os, subprocess
env = {}
for line in open(".env"):
    k, _, v = line.rstrip("\n").partition("=")
    if k and not k.startswith("#"):
        env[k] = v
def mounts(name):
    try:
        out = subprocess.check_output(["docker", "inspect", name], stderr=subprocess.DEVNULL)
        return json.loads(out)[0].get("Mounts", [])
    except Exception:
        return []
# The service's own folders inside its container: a library mount there would replace them.
RESERVED = ("/app", "/data", "/sonarr", "/prowlarr", "/plex")
def clashes(d):
    return d in ("", "/") or any(d == r or d.startswith(r + "/") or r.startswith(d + "/") for r in RESERVED)
roots = []
plex = mounts(env.get("PLEX_CONTAINER") or "plex")
for m in mounts(env.get("SONARR_CONTAINER") or "sonarr"):
    hs, sd = m["Source"].rstrip("/"), m["Destination"].rstrip("/")
    found = []
    for p in plex:
        hp, pd = p["Source"].rstrip("/"), p["Destination"].rstrip("/")
        if not hs or not hp:
            continue
        if hs == hp or hs.startswith(hp + "/"):          # Sonarr's folder is inside Plex's: all of it
            found = [(hs, sd, pd + hs[len(hp):])]
            break
        if hp.startswith(hs + "/"):                       # Plex's folders inside Sonarr's: each of them
            found.append((hp, sd + hp[len(hs):], pd))
    for root in found:
        if clashes(root[1]):
            print("    season folders: not mounting " + root[1] + " -- the service uses that path itself")
        elif root not in roots:
            roots.append(root)
            print("    season folders: " + root[0] + " (Sonarr " + root[1] + ", Plex " + root[2] + ")")
on = (env.get("SEASON_FOLDERS") or "true").lower() == "true" and bool(roots)
lines = [l for l in open(".env") if not l.startswith("LIBRARY_MAP=")]
lines.append("LIBRARY_MAP=" + ("|".join(">".join(r) for r in roots) if on else "") + "\n")
with open(".env.tmp", "w") as f:
    f.writelines(lines)
os.chmod(".env.tmp", 0o600)
os.replace(".env.tmp", ".env")
if on:
    with open("docker-compose.override.yml", "w") as f:
        f.write("# Written by deploy.sh: the TV library at Sonarr's paths, for season folders.\n")
        f.write("services:\n  automatic:\n    volumes:\n")
        for h, s, _ in roots:
            f.write("      - " + json.dumps(h + ":" + s) + "\n")
elif os.path.exists("docker-compose.override.yml"):
    os.remove("docker-compose.override.yml")
print("    season folders:", ("%d library folders" % len(roots)) if on else "off")
PY
docker compose up -d --force-recreate 2>&1 | tail -2
sleep 3
docker logs --tail 4 magnet-automatic 2>&1
REMOTE

if [[ "${1:-}" == "--token" ]]; then
  DIR="$HOME/Library/Application Support/Magnet"
  mkdir -p "$DIR" && chmod 700 "$DIR"
  ( umask 077; "${SSH[@]}" "grep '^API_TOKEN=' '$MAGNET_NAS_DIR/.env' | cut -d= -f2-" > "$DIR/automatic-token.tmp" )
  [[ -s "$DIR/automatic-token.tmp" ]] && mv "$DIR/automatic-token.tmp" "$DIR/automatic-token" && chmod 600 "$DIR/automatic-token"
  echo "==> API token copied to $DIR/automatic-token"
fi
echo "==> Done"
